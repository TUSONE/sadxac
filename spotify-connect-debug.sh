#!/usr/bin/env bash
# Temporary, scoped Connect logging. Does not change cache, credentials or audio format.
set -euo pipefail
[[ $(id -un) == tusone ]] || { echo 'Run as tusone' >&2; exit 1; }
mode=${1:-}
[[ "$mode" == on || "$mode" == off ]] || { echo 'Usage: bash spotify-connect-debug.sh on|off' >&2; exit 1; }
sudo -v
sudo systemctl cat slavik-spotify >/dev/null
path=/etc/systemd/system/slavik-spotify.service.d/90-slavik-debug.conf
if [[ "$mode" == on ]]; then
    temporary=$(mktemp)
    trap 'rm -f "$temporary"' EXIT
    cat > "$temporary" <<'UNIT'
[Service]
Environment=RUST_LOG=info,librespot_connect::spirc=debug,librespot_connect::state=debug
UNIT
    sudo mkdir -p /etc/systemd/system/slavik-spotify.service.d
    if sudo test -f "$path"; then
        sudo cmp -s "$temporary" "$path" || { echo 'Existing debug override differs; preserve it.' >&2; exit 1; }
    fi
    sudo install -m 644 -o root -g root "$temporary" "$path"
else
    # Only remove the exact override generated by this script.
    if sudo test -f "$path"; then
        temporary=$(mktemp)
        trap 'rm -f "$temporary"' EXIT
        cat > "$temporary" <<'UNIT'
[Service]
Environment=RUST_LOG=info,librespot_connect::spirc=debug,librespot_connect::state=debug
UNIT
        sudo cmp -s "$temporary" "$path" || { echo 'Override differs; preserve it.' >&2; exit 1; }
        sudo rm -- "$path"
    fi
fi
sudo systemctl daemon-reload
sudo systemctl restart slavik-spotify
printf '%s\n' "Connect debug $mode. Select Slavik again in Spotify."
